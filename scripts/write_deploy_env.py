#!/usr/bin/env python3
"""Generate non-secret env override files for deploy_data-backed runtime wiring."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DEPLOY_ROOT = PROJECT_ROOT / "deploy_data"
DEFAULT_BACKEND_ENV = PROJECT_ROOT / "backend" / ".env.deploy-data"
DEFAULT_DOCKER_ENV = PROJECT_ROOT / "docker" / ".env.deploy-data"
DEFAULT_DOCKER_FOLDSEEK_BINARY = "/usr/local/bin/foldseek"


def _discover(root: Path, *parts: str) -> str:
    candidate = root.joinpath(*parts)
    return str(candidate) if candidate.exists() else ""


def _render_lines(mapping: dict[str, str]) -> str:
    lines = [
        "# Generated by scripts/write_deploy_env.py",
        "# Non-secret deploy-data overrides only.",
    ]
    for key, value in mapping.items():
        lines.append(f"{key}={value}")
    lines.append("")
    return "\n".join(lines)


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _resolve_host_foldseek_binary(explicit: str) -> str:
    if explicit.strip():
        return explicit.strip()
    discovered = shutil.which("foldseek")
    if discovered:
        return discovered
    candidate = Path.home() / "tools" / "foldseek" / "bin" / "foldseek"
    if candidate.exists():
        return str(candidate.resolve())
    return ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--deploy-root", default=str(DEFAULT_DEPLOY_ROOT), help="Host deploy_data root")
    parser.add_argument("--backend-out", default=str(DEFAULT_BACKEND_ENV), help="Output backend env override file")
    parser.add_argument("--docker-out", default=str(DEFAULT_DOCKER_ENV), help="Output docker env override file")
    parser.add_argument("--foldseek-api-url", default="", help="Optional live Foldseek HTTP endpoint")
    parser.add_argument("--foldseek-binary", default="", help="Optional Foldseek CLI binary path/name")
    parser.add_argument(
        "--docker-foldseek-binary",
        default=DEFAULT_DOCKER_FOLDSEEK_BINARY,
        help="Foldseek binary path to use inside Docker containers",
    )
    args = parser.parse_args()

    deploy_root = Path(args.deploy_root).expanduser().resolve()
    backend_out = Path(args.backend_out).expanduser().resolve()
    docker_out = Path(args.docker_out).expanduser().resolve()
    host_foldseek_binary = _resolve_host_foldseek_binary(args.foldseek_binary)

    backend_values = {
        "DEPLOY_DATA_ROOT": str(deploy_root),
        "LOCAL_ANNOTATION_FIXTURE_PATH": _discover(deploy_root, "annotations"),
        "SIFTS_MAPPING_PATH": _discover(deploy_root, "sifts"),
        "FOLDSEEK_DATABASE_ROOT": _discover(deploy_root, "foldseek"),
        "STRUCTURE_SMOKE_PDB_FILE": _discover(deploy_root, "smoke", "query.pdb"),
        "LIPASE_DB_PATH": _discover(deploy_root, "lipase", "lipase.db"),
        "FOLDSEEK_API_URL": args.foldseek_api_url.strip(),
        "FOLDSEEK_BINARY": host_foldseek_binary,
    }
    docker_values = {
        "DEPLOY_DATA_HOST_PATH": str(deploy_root),
        "LIPASE_DB_PATH": "/app/deploy_data/lipase/lipase.db",
        "FOLDSEEK_API_URL": args.foldseek_api_url.strip(),
        "FOLDSEEK_BINARY": args.docker_foldseek_binary.strip() if args.docker_foldseek_binary.strip() else host_foldseek_binary,
    }

    _write(backend_out, _render_lines(backend_values))
    _write(docker_out, _render_lines(docker_values))

    print(f"Wrote backend overrides: {backend_out}")
    print(f"Wrote docker overrides: {docker_out}")
    print("Suggested usage:")
    print(f"  backend: set env_file to include {backend_out.name} or source it before local runs")
    print(f"  docker: docker compose --env-file .env --env-file {docker_out.name} up -d")
    print(f"  docker foldseek binary: {docker_values['FOLDSEEK_BINARY'] or '(unset)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
