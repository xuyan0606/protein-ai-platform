#!/usr/bin/env bash
# =============================================================================
# Protein AI Platform — Alibaba Cloud Managed Deployment Helper
# =============================================================================
# Target topology:
#   ECS-App-01 / ECS-App-02 -> docker-compose.aliyun-app.yml
#   ECS-GPU-01              -> docker-compose.aliyun-gpu.yml
#   Managed services        -> RDS PostgreSQL + Cloud Redis + OSS
#
# Usage:
#   chmod +x deploy-aliyun.sh
#   ./deploy-aliyun.sh app
#   ./deploy-aliyun.sh gpu
#   ./deploy-aliyun.sh app config
#   ./deploy-aliyun.sh app ps
#   ./deploy-aliyun.sh gpu logs
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DOCKER_DIR="$SCRIPT_DIR/docker"

ROLE="${1:-}"
ACTION="${2:-up}"
REQUIRE_RELEASE_MANIFEST="${REQUIRE_RELEASE_MANIFEST:-1}"
PYTHON="${PYTHON:-python3}"
ALLOW_LEGACY_RELEASE="${ALLOW_LEGACY_RELEASE:-0}"
RELEASE_MANIFEST="${RELEASE_MANIFEST:-$SCRIPT_DIR/RELEASE-MANIFEST.json}"
RELEASE_ENV_FILE=""

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[INFO]${NC} $*"; }
warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
err()  { echo -e "${RED}[ERROR]${NC} $*"; }

usage() {
    cat <<'EOF'
Usage:
  ./deploy-aliyun.sh <role> [action]

Roles:
  app   Deploy ECS-App-01 / ECS-App-02 application node stack
  gpu   Deploy ECS-GPU-01 dedicated MD/GPU worker

Actions:
  up     Build and start the selected role stack (default)
  build  Build images only
  config Validate compose rendering only
  ps     Show compose service status
  logs   Tail compose logs
  down   Stop the selected role stack

Release provenance:
  A RELEASE-MANIFEST.json with digest-pinned images is required by default.
  Set ALLOW_LEGACY_RELEASE=1 only for an explicitly unverified legacy release.

Required files:
  docker/.env
  docker/.env.deploy-data          (generated by scripts/write_deploy_env.py)
  docker/.env.aliyun.app           for role=app
  docker/.env.aliyun.gpu           for role=gpu
  RELEASE-MANIFEST.json             for config/build/up (digest-pinned release)
EOF
}

if [ -z "$ROLE" ]; then
    usage
    exit 1
fi

case "$ROLE" in
    app)
        COMPOSE_FILE="$DOCKER_DIR/docker-compose.aliyun-app.yml"
        ROLE_ENV="$DOCKER_DIR/.env.aliyun.app"
        ;;
    gpu)
        COMPOSE_FILE="$DOCKER_DIR/docker-compose.aliyun-gpu.yml"
        ROLE_ENV="$DOCKER_DIR/.env.aliyun.gpu"
        ;;
    *)
        err "Unknown role: $ROLE"
        usage
        exit 1
        ;;
esac

BASE_ENV="$DOCKER_DIR/.env"
DEPLOY_ENV="$DOCKER_DIR/.env.deploy-data"

require_file() {
    local path="$1"
    local hint="$2"
    if [ ! -f "$path" ]; then
        err "Missing file: $path"
        echo "Hint: $hint"
        exit 1
    fi
}

ensure_docker() {
    if ! command -v docker >/dev/null 2>&1; then
        err "Docker is not installed."
        echo "Install Docker first, then re-run this script."
        exit 1
    fi
    if ! docker compose version >/dev/null 2>&1; then
        err "Docker Compose plugin is not available."
        echo "Install docker compose plugin first, then re-run this script."
        exit 1
    fi
}

maybe_generate_deploy_env() {
    if [ -f "$DEPLOY_ENV" ]; then
        return
    fi
    if [ -d "$SCRIPT_DIR/deploy_data" ] && command -v python3 >/dev/null 2>&1; then
        log "docker/.env.deploy-data missing; generating it from deploy_data/"
        (cd "$SCRIPT_DIR" && python3 scripts/write_deploy_env.py --deploy-root deploy_data)
    fi
}

compose_cmd() {
    (
        cd "$DOCKER_DIR"
        local args=(
            docker compose \
            --env-file .env \
            --env-file "$(basename "$ROLE_ENV")" \
            --env-file "$(basename "$DEPLOY_ENV")" \
        )
        if [ -n "$RELEASE_ENV_FILE" ] && [ -f "$RELEASE_ENV_FILE" ]; then
            args+=(--env-file "$RELEASE_ENV_FILE")
        fi
        args+=(-f "$(basename "$COMPOSE_FILE")")
        "${args[@]}" "$@"
    )
}

release_manifest_active() {
    [ "$REQUIRE_RELEASE_MANIFEST" = "1" ] && [ "$ALLOW_LEGACY_RELEASE" != "1" ]
}

load_release_manifest() {
    if ! release_manifest_active; then
        if [ ! -f "$RELEASE_MANIFEST" ]; then
            warn "legacy release explicitly allowed; provenance is unverified"
        fi
        return
    fi
    require_file "$RELEASE_MANIFEST" "build RELEASE-MANIFEST.json with scripts/release_provenance.py"
    require_file "$SCRIPT_DIR/scripts/release_provenance.py" "release provenance helper is missing"
    require_file "$SCRIPT_DIR/scripts/check_report_version_alignment.py" "report version alignment helper is missing"
    "$PYTHON" "$SCRIPT_DIR/scripts/release_provenance.py" \
        --root "$SCRIPT_DIR" verify --offline --manifest "$RELEASE_MANIFEST" \
        --env-file "$ROLE_ENV" --require-compose-file "$COMPOSE_FILE"
    "$PYTHON" "$SCRIPT_DIR/scripts/check_report_version_alignment.py" \
        --root "$SCRIPT_DIR" --manifest "$RELEASE_MANIFEST" --offline
    RELEASE_ENV_FILE="$(mktemp "${TMPDIR:-/tmp}/protein-ai-release-env.XXXXXX")"
    trap 'if [ -n "${RELEASE_ENV_FILE:-}" ]; then rm -f "$RELEASE_ENV_FILE"; fi' EXIT
    "$PYTHON" "$SCRIPT_DIR/scripts/release_provenance.py" \
        --root "$SCRIPT_DIR" compose-env --manifest "$RELEASE_MANIFEST" > "$RELEASE_ENV_FILE"
    chmod 600 "$RELEASE_ENV_FILE"
    log "release manifest verified: $(sed -n 's/^RELEASE_ID=//p' "$RELEASE_ENV_FILE")"
}

release_image() {
    local variable="$1"
    [ -n "$RELEASE_ENV_FILE" ] && [ -f "$RELEASE_ENV_FILE" ] || return 1
    sed -n "s/^${variable}=//p" "$RELEASE_ENV_FILE" | head -n 1
}

verify_runtime_image() {
    local service="$1"
    local expected="$2"
    local container_id actual repo_digests
    container_id="$(compose_cmd ps -q "$service" | tail -n 1 | tr -d '\r')"
    [ -n "$container_id" ] || { err "No running container found for service=$service"; return 1; }
    actual="$(docker inspect --format '{{.Config.Image}}' "$container_id")"
    [ "$actual" = "$expected" ] || {
        err "Runtime image mismatch service=$service expected=$expected actual=$actual"
        return 1
    }
    repo_digests="$(docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$actual" 2>/dev/null || true)"
    printf '%s\n' "$repo_digests" | grep -Fxq "$expected" || {
        err "Runtime image digest unavailable or mismatched service=$service expected=$expected"
        return 1
    }
}

verify_runtime_images() {
    release_manifest_active || return 0
    local backend frontend worker md_worker ligand
    backend="$(release_image BACKEND_IMAGE)"
    frontend="$(release_image FRONTEND_IMAGE)"
    worker="$(release_image WORKER_IMAGE)"
    md_worker="$(release_image MD_WORKER_IMAGE)"
    ligand="$(release_image LIGAND_WORKER_IMAGE)"
    if [ "$ROLE" = "app" ]; then
        verify_runtime_image backend "$backend"
        verify_runtime_image worker "$worker"
        verify_runtime_image md-worker "$md_worker"
        verify_runtime_image frontend "$frontend"
        verify_runtime_image ligand-worker "$ligand"
    else
        verify_runtime_image md-worker "$md_worker"
        verify_runtime_image ligand-worker "$ligand"
    fi
    log "runtime image digests match release manifest"
}

backup_chroma_before_upgrade() {
    [ "$ROLE" = "app" ] || return 0
    local container_id running backup_dir
    container_id="$(compose_cmd ps --all -q chromadb | head -n 1 | tr -d '\r')"
    if [ -z "$container_id" ]; then
        if [ "${ALLOW_CHROMA_UNBACKED_INSTALL:-0}" = "1" ]; then
            warn "explicitly allowed initial install without an existing Chroma container"
            return 0
        fi
        err "No existing Chroma container found; refusing to upgrade without a verified volume backup. Set ALLOW_CHROMA_UNBACKED_INSTALL=1 only for a confirmed empty first install."
        return 1
    fi
    running="$(docker inspect --format '{{.State.Running}}' "$container_id")"
    backup_dir="${CHROMA_BACKUP_DIR:-$SCRIPT_DIR/backups/chroma}"
    if [ "$running" = "true" ]; then
        compose_cmd stop chromadb >/dev/null || return 1
    fi
    if ! "$SCRIPT_DIR/scripts/backup_chroma_volume.sh" "$container_id" "$backup_dir"; then
        if [ "$running" = "true" ]; then
            compose_cmd start chromadb >/dev/null || warn "Failed to restart Chroma after backup failure; manual recovery is required"
        fi
        err "Chroma volume backup failed; release update aborted"
        return 1
    fi
    if [ "$running" = "true" ]; then
        compose_cmd start chromadb >/dev/null || {
            err "Chroma backup exists but the previous container could not be restarted; release update aborted"
            return 1
        }
    fi
}

ensure_docker
require_file "$BASE_ENV" "cp docker/.env.example docker/.env && fill shared secrets"
require_file "$ROLE_ENV" "cp ${ROLE_ENV}.example $ROLE_ENV && fill Alibaba Cloud values"
maybe_generate_deploy_env
require_file "$DEPLOY_ENV" "run: python3 scripts/write_deploy_env.py --deploy-root deploy_data"

load_release_manifest

log "Validating compose for role=$ROLE"
compose_cmd config >/dev/null

case "$ACTION" in
    config)
        log "Compose configuration rendered successfully."
        ;;
    build)
        if release_manifest_active; then
            err "build is disabled for a manifest release; build/push digest-pinned images before creating RELEASE-MANIFEST.json"
            exit 1
        fi
        log "Building images for role=$ROLE"
        compose_cmd build --parallel
        ;;
    up)
        backup_chroma_before_upgrade
        if release_manifest_active; then
            log "Pulling digest-pinned images from release manifest"
            compose_cmd pull md-worker ligand-worker backend worker frontend 2>/dev/null || compose_cmd pull
        else
            log "Building images for legacy release"
            compose_cmd build --parallel
        fi
        log "Starting services for role=$ROLE"
        compose_cmd up -d
        verify_runtime_images
        log "Current status:"
        compose_cmd ps
        ;;
    ps)
        verify_runtime_images
        compose_cmd ps
        ;;
    logs)
        compose_cmd logs -f
        ;;
    down)
        log "Stopping services for role=$ROLE"
        compose_cmd down
        ;;
    *)
        err "Unknown action: $ACTION"
        usage
        exit 1
        ;;
esac

if [ "$ACTION" = "up" ]; then
    echo ""
    if [ "$ROLE" = "app" ]; then
        log "App node ready. Expected public entry: ${PUBLIC_BASE_URL:-set in docker/.env.aliyun.app}"
        echo "Next:"
        echo "  1. Run Outline migrations once: docker compose -f docker/docker-compose.aliyun-app.yml exec outline yarn db:migrate"
        echo "  2. Verify /api/health, /wiki, /pdb, and deploy-live-gate"
        echo "  3. Reuse the same compose/env set on ECS-App-02 for standby/failover"
    else
        log "GPU worker stack ready."
        echo "Next:"
        echo "  1. Confirm NVIDIA Container Toolkit is installed if real GPU execution is required"
        echo "  2. Submit one short MD task and verify artifacts land in OSS"
        echo "  3. Keep ECS-GPU-01 isolated from public ingress; it only needs Redis/RDS/OSS egress"
    fi
fi
