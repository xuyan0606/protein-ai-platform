#!/usr/bin/env bash
# =============================================================================
# Protein AI Platform — Alibaba Cloud Managed Deployment Helper
# =============================================================================
# Target topology:
#   ECS-App-01 / ECS-App-02 -> docker-compose.aliyun-app.yml
#   ECS-GPU-01              -> docker-compose.aliyun-gpu.yml
#   Managed services        -> RDS PostgreSQL + Cloud Redis + OSS
#
# Usage:
#   chmod +x deploy-aliyun.sh
#   ./deploy-aliyun.sh app
#   ./deploy-aliyun.sh gpu
#   ./deploy-aliyun.sh app config
#   ./deploy-aliyun.sh app ps
#   ./deploy-aliyun.sh gpu logs
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DOCKER_DIR="$SCRIPT_DIR/docker"

ROLE="${1:-}"
ACTION="${2:-up}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[INFO]${NC} $*"; }
warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
err()  { echo -e "${RED}[ERROR]${NC} $*"; }

usage() {
    cat <<'EOF'
Usage:
  ./deploy-aliyun.sh <role> [action]

Roles:
  app   Deploy ECS-App-01 / ECS-App-02 application node stack
  gpu   Deploy ECS-GPU-01 dedicated MD/GPU worker

Actions:
  up     Build and start the selected role stack (default)
  build  Build images only
  config Validate compose rendering only
  ps     Show compose service status
  logs   Tail compose logs
  down   Stop the selected role stack

Required files:
  docker/.env
  docker/.env.deploy-data          (generated by scripts/write_deploy_env.py)
  docker/.env.aliyun.app           for role=app
  docker/.env.aliyun.gpu           for role=gpu
EOF
}

if [ -z "$ROLE" ]; then
    usage
    exit 1
fi

case "$ROLE" in
    app)
        COMPOSE_FILE="$DOCKER_DIR/docker-compose.aliyun-app.yml"
        ROLE_ENV="$DOCKER_DIR/.env.aliyun.app"
        ;;
    gpu)
        COMPOSE_FILE="$DOCKER_DIR/docker-compose.aliyun-gpu.yml"
        ROLE_ENV="$DOCKER_DIR/.env.aliyun.gpu"
        ;;
    *)
        err "Unknown role: $ROLE"
        usage
        exit 1
        ;;
esac

BASE_ENV="$DOCKER_DIR/.env"
DEPLOY_ENV="$DOCKER_DIR/.env.deploy-data"

require_file() {
    local path="$1"
    local hint="$2"
    if [ ! -f "$path" ]; then
        err "Missing file: $path"
        echo "Hint: $hint"
        exit 1
    fi
}

ensure_docker() {
    if ! command -v docker >/dev/null 2>&1; then
        err "Docker is not installed."
        echo "Install Docker first, then re-run this script."
        exit 1
    fi
    if ! docker compose version >/dev/null 2>&1; then
        err "Docker Compose plugin is not available."
        echo "Install docker compose plugin first, then re-run this script."
        exit 1
    fi
}

maybe_generate_deploy_env() {
    if [ -f "$DEPLOY_ENV" ]; then
        return
    fi
    if [ -d "$SCRIPT_DIR/deploy_data" ] && command -v python3 >/dev/null 2>&1; then
        log "docker/.env.deploy-data missing; generating it from deploy_data/"
        (cd "$SCRIPT_DIR" && python3 scripts/write_deploy_env.py --deploy-root deploy_data)
    fi
}

compose_cmd() {
    (
        cd "$DOCKER_DIR"
        docker compose \
            --env-file .env \
            --env-file "$(basename "$ROLE_ENV")" \
            --env-file "$(basename "$DEPLOY_ENV")" \
            -f "$(basename "$COMPOSE_FILE")" \
            "$@"
    )
}

ensure_docker
require_file "$BASE_ENV" "cp docker/.env.example docker/.env && fill shared secrets"
require_file "$ROLE_ENV" "cp ${ROLE_ENV}.example $ROLE_ENV && fill Alibaba Cloud values"
maybe_generate_deploy_env
require_file "$DEPLOY_ENV" "run: python3 scripts/write_deploy_env.py --deploy-root deploy_data"

log "Validating compose for role=$ROLE"
compose_cmd config >/dev/null

case "$ACTION" in
    config)
        log "Compose configuration rendered successfully."
        ;;
    build)
        log "Building images for role=$ROLE"
        compose_cmd build --parallel
        ;;
    up)
        log "Building images for role=$ROLE"
        compose_cmd build --parallel
        log "Starting services for role=$ROLE"
        compose_cmd up -d
        log "Current status:"
        compose_cmd ps
        ;;
    ps)
        compose_cmd ps
        ;;
    logs)
        compose_cmd logs -f
        ;;
    down)
        log "Stopping services for role=$ROLE"
        compose_cmd down
        ;;
    *)
        err "Unknown action: $ACTION"
        usage
        exit 1
        ;;
esac

if [ "$ACTION" = "up" ]; then
    echo ""
    if [ "$ROLE" = "app" ]; then
        log "App node ready. Expected public entry: ${PUBLIC_BASE_URL:-set in docker/.env.aliyun.app}"
        echo "Next:"
        echo "  1. Run Outline migrations once: docker compose -f docker/docker-compose.aliyun-app.yml exec outline yarn db:migrate"
        echo "  2. Verify /api/health, /wiki, /pdb, and deploy-live-gate"
        echo "  3. Reuse the same compose/env set on ECS-App-02 for standby/failover"
    else
        log "GPU worker stack ready."
        echo "Next:"
        echo "  1. Confirm NVIDIA Container Toolkit is installed if real GPU execution is required"
        echo "  2. Submit one short MD task and verify artifacts land in OSS"
        echo "  3. Keep ECS-GPU-01 isolated from public ingress; it only needs Redis/RDS/OSS egress"
    fi
fi
