def canonical_sha256(payload: Any) -> str:
    encoded = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def command_contract_sha256(commands: list[list[str]]) -> str:
    return canonical_sha256({"version": COMMAND_CONTRACT_VERSION, "commands": commands})


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fsync_directory(path: Path) -> None:
    descriptor = os.open(path, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def write_json_atomic(path: Path, payload: dict[str, Any], *, fail_before_replace: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    encoded = (json.dumps(payload, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    descriptor, temp_name = tempfile.mkstemp(prefix=f".{path.name}.receipt-", dir=path.parent)
    temp_path = Path(temp_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(encoded)
            handle.flush()
            os.fsync(handle.fileno())
        if path.exists():
            os.chmod(temp_path, path.stat().st_mode)
        if fail_before_replace:
            raise RuntimeError("simulated_safe_pipeline_receipt_failure_before_replace")
        os.replace(temp_path, path)
        fsync_directory(path.parent)
    finally:
        if temp_path.exists():
            temp_path.unlink()


def acquire_run_lock(path: Path, timeout_seconds: float):
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = path.open("a+")
    deadline = time.monotonic() + max(timeout_seconds, 0.0)
    while True:
        try:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            handle.seek(0)
            handle.truncate()
            handle.write(f"pid={os.getpid()}\n")
            handle.flush()
            os.fsync(handle.fileno())
            return handle
        except BlockingIOError:
            if time.monotonic() >= deadline:
                handle.close()
                return None
            time.sleep(0.05)


def run_step(command: list[str]) -> dict[str, Any]:
    python_executable = sys.executable
    command_args = command
    if len(command) >= 3 and command[0] == "--python":
        python_executable = str(AI_ROOT / command[1])
        command_args = command[2:]
        if not Path(python_executable).exists():
            return {
                "command": " ".join([python_executable, *command_args]),
                "returncode": 0,
                "stdout": json.dumps({
                    "status": "skipped_optional_python_runtime_missing",
                    "missing_python": python_executable,
                    "script": command_args[0] if command_args else None,
                    "safe_for_model_claim": False,
                }, ensure_ascii=False),
                "stderr": "",
            }
    try:
        environment = os.environ.copy()
        environment["KWB_DEFER_SAFE_PIPELINE_TERMINAL"] = "1"
        process = subprocess.run(
            [python_executable, *command_args],
            cwd=AI_ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
            env=environment,
        )
    except FileNotFoundError as exc:
        return {
            "command": " ".join([python_executable, *command_args]),
            "returncode": 127,
            "stdout": "",
            "stderr": f"not_found:{exc}",
        }
    return {
        "command": " ".join([python_executable, *command_args]),
        "returncode": process.returncode,
        "stdout": process.stdout.strip(),
        "stderr": process.stderr.strip(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Run local safe training pipeline")
    parser.add_argument("--output", type=Path, default=OUT)
    parser.add_argument("--lock-path", type=Path, default=LOCK_PATH)
    parser.add_argument("--lock-timeout-seconds", type=float, default=30.0)
    parser.add_argument("--continue-on-error", action="store_true")
    args = parser.parse_args()

    lock_handle = acquire_run_lock(args.lock_path, args.lock_timeout_seconds)
    if lock_handle is None:
        report = {
            "created_at": datetime.now(timezone.utc).isoformat(),
            "steps_requested": len(COMMANDS),
            "steps_run": 0,
            "failed_steps": 1,
            "success": False,
            "lock_path": str(args.lock_path.resolve()),
            "lock_acquired": False,
            "failure_count": 1,
            "failures": [{"check": "safe_pipeline_lock_acquired", "expected": True}],
            "safe_for_model_claim": False,
            "release_ready": False,
            "note": "Runs local files only; no server sync or external downloads.",
        }
        if args.output.resolve() != OUT.resolve():
            write_json_atomic(args.output, report)
        print(json.dumps({
            "steps_run": 0,
            "failed_steps": 1,
            "success": False,
            "lock_acquired": False,
            "output": str(args.output),
        }, ensure_ascii=False))
        return 1

    receipt_committed = False
    receipt_error = ""
    try:
        steps = []
        for command in COMMANDS:
            result = run_step(command)
            steps.append(result)
            if result["returncode"] != 0 and not args.continue_on_error:
                break

        failed = [step for step in steps if step["returncode"] != 0]
        runner_script = Path(__file__).resolve()
        report = {
            "created_at": datetime.now(timezone.utc).isoformat(),
            "steps_requested": len(COMMANDS),
            "steps_run": len(steps),
            "failed_steps": len(failed),
            "success": not failed,
            "runner_script_path": str(runner_script),
            "runner_script_sha256": sha256(runner_script),
            "command_contract_version": COMMAND_CONTRACT_VERSION,
            "command_contract_sha256": command_contract_sha256(COMMANDS),
            "command_contract_rows": len(COMMANDS),
            "output_path": str(args.output.resolve()),
            "lock_path": str(args.lock_path.resolve()),
            "lock_acquired": True,
            "receipt_atomic_commit": True,
            "failure_count": len(failed),
            "failures": [
                {"check": "pipeline_step_returncode", "command": step["command"], "returncode": step["returncode"]}
                for step in failed
            ],
            "steps": steps,
            "safe_for_model_claim": False,
            "release_ready": False,
            "note": "Runs local files only; no server sync or external downloads.",
        }
        try:
            write_json_atomic(args.output, report)
            receipt_committed = True
        except Exception as exc:
            receipt_error = f"{type(exc).__name__}:{exc}"
    finally:
        fcntl.flock(lock_handle.fileno(), fcntl.LOCK_UN)
        lock_handle.close()
    print(json.dumps({
        "steps_run": report["steps_run"],
        "failed_steps": report["failed_steps"],
        "success": report["success"] and receipt_committed,
        "lock_acquired": True,
        "receipt_committed": receipt_committed,
        "receipt_error": receipt_error,
        "output": str(args.output),
    }, ensure_ascii=False))
    return 0 if report["success"] and receipt_committed else 1


if __name__ == "__main__":
    raise SystemExit(main())
