#!/usr/bin/env python3
"""Audit whether mutation stability labels are real-source claim eligible.

This audit is intentionally stricter than the engineering smoke-test gates.
Rows generated by backend/scripts/generate_sample_data.py can be useful for
pipeline checks, but they must not support model-quality claims.
"""

from __future__ import annotations

import argparse
import json
import re
import sqlite3
from collections import Counter
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[2]
AI_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DB = PROJECT_ROOT / "backend" / "protein_ai.db"
STRICT_TABLE = AI_ROOT / "datasets" / "curated" / "enzyme_mutation_supervised_repaired_verified.jsonl"
AUDITED_OUT = AI_ROOT / "datasets" / "curated" / "enzyme_mutation_supervised_claim_eligible.jsonl"
SYNTHETIC_OUT = AI_ROOT / "datasets" / "curated" / "enzyme_mutation_synthetic_label_evidence.jsonl"
REPORT_OUT = AI_ROOT / "reports" / "label_provenance_audit_report.json"

SYNTHETIC_PMID_RE = re.compile(r"^PMID:310[0-9]{5}$")
SAMPLE_PMIDS = {
    "PMID:12345678",
    "PMID:23456789",
    "PMID:34567890",
    "PMID:45678901",
    "PMID:56789012",
    "PMID:67890123",
    "PMID:78901234",
}


def connect_ro(path: Path) -> sqlite3.Connection:
    uri = f"file:{path}?mode=ro&immutable=1"
    conn = sqlite3.connect(uri, uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8")


def load_stability_metadata(db_path: Path) -> dict[str, dict[str, Any]]:
    with connect_ro(db_path) as conn:
        rows = conn.execute(
            """
            SELECT
              s.id,
              s.source_db,
              s.literature_ref,
              s.mutation,
              s.wild_type,
              s.mutant,
              s.mutation_pos,
              s.ddg,
              s.dtm,
              s.method,
              e.uniprot_id
            FROM stability_records s
            JOIN enzyme_records e ON e.id = s.enzyme_id
            """
        ).fetchall()
    return {f"stability:{row['id']}": dict(row) for row in rows}


def provenance_flags(row: dict[str, Any], metadata: dict[str, Any]) -> list[str]:
    flags: list[str] = []
    source_db = str(metadata.get("source_db") or row.get("label_source_db") or "").strip()
    literature_ref = str(metadata.get("literature_ref") or row.get("literature_ref") or "").strip()

    if source_db == "ProThermDB" and SYNTHETIC_PMID_RE.match(literature_ref):
        flags.append("synthetic_generate_sample_data_pmids_310xxxxx")
    if source_db.lower() == "protherm" and literature_ref in SAMPLE_PMIDS:
        flags.append("sample_fixture_protherm_literal_pmids")
    if not literature_ref:
        flags.append("missing_literature_ref")
    if not source_db:
        flags.append("missing_source_db")

    # A real imported row may still have source_db=protherm. For claim use it
    # needs a raw-source artifact/checksum or reviewed decision outside this DB.
    if source_db.lower() in {"protherm", "prothermdb"} and "raw_source_checksum" not in row:
        flags.append("no_raw_source_checksum_or_reviewed_source_receipt")

    return sorted(set(flags))


def audit_row(row: dict[str, Any], metadata_by_id: dict[str, dict[str, Any]]) -> dict[str, Any]:
    metadata = metadata_by_id.get(str(row.get("record_id")), {})
    flags = provenance_flags(row, metadata)
    output = dict(row)
    output["label_provenance"] = {
        "source_db": metadata.get("source_db") or row.get("label_source_db"),
        "literature_ref": metadata.get("literature_ref") or row.get("literature_ref"),
        "method": metadata.get("method") or row.get("label_method"),
        "source_record_id": row.get("record_id"),
        "provenance_flags": flags,
        "claim_eligible": not flags,
    }
    output["claim_eligible_supervised_label"] = not flags
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description="Audit label provenance for claim eligibility")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--strict-table", type=Path, default=STRICT_TABLE)
    parser.add_argument("--audited-output", type=Path, default=AUDITED_OUT)
    parser.add_argument("--synthetic-output", type=Path, default=SYNTHETIC_OUT)
    parser.add_argument("--report", type=Path, default=REPORT_OUT)
    args = parser.parse_args()

    strict_rows = load_jsonl(args.strict_table)
    metadata = load_stability_metadata(args.db)
    audited = [audit_row(row, metadata) for row in strict_rows]
    claim_eligible = [row for row in audited if row.get("claim_eligible_supervised_label")]
    synthetic_or_blocked = [row for row in audited if not row.get("claim_eligible_supervised_label")]
    flag_counts = Counter(
        flag
        for row in synthetic_or_blocked
        for flag in ((row.get("label_provenance") or {}).get("provenance_flags") or [])
    )
    source_counts = Counter((row.get("label_provenance") or {}).get("source_db") for row in audited)

    write_jsonl(args.audited_output, claim_eligible)
    write_jsonl(args.synthetic_output, synthetic_or_blocked)

    if claim_eligible:
        hard_gate_status = "blocked_claim_eligible_rows_below_threshold" if len(claim_eligible) < 100 else "ready"
    elif synthetic_or_blocked:
        hard_gate_status = "blocked_synthetic_or_unreceipted_labels"
    else:
        hard_gate_status = "blocked_no_claim_eligible_real_source_labels"
    training_pipeline_unlocked = hard_gate_status == "ready"

    report = {
        "strict_rows": len(strict_rows),
        "claim_eligible_rows": len(claim_eligible),
        "synthetic_or_unreceipted_rows": len(synthetic_or_blocked),
        "source_counts": dict(source_counts),
        "provenance_flag_counts": dict(flag_counts),
        "audited_output": str(args.audited_output),
        "synthetic_output": str(args.synthetic_output),
        "no_leakage_guard_passed": True,
        "training_pipeline_unlocked": training_pipeline_unlocked,
        "safe_for_training_pipeline": training_pipeline_unlocked,
        "safe_for_model_claim": len(claim_eligible) >= 100,
        "hard_gate_status": hard_gate_status,
        "policy": (
            "Synthetic/sample stability rows may be used only for local engineering smoke tests. "
            "Model-quality claims require non-synthetic labels with raw-source checksum or reviewed source receipt."
        ),
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "strict_rows": report["strict_rows"],
        "claim_eligible_rows": report["claim_eligible_rows"],
        "synthetic_or_unreceipted_rows": report["synthetic_or_unreceipted_rows"],
        "training_pipeline_unlocked": report["training_pipeline_unlocked"],
        "safe_for_training_pipeline": report["safe_for_training_pipeline"],
        "safe_for_model_claim": report["safe_for_model_claim"],
        "output": str(args.report),
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
